import { test, expect } from '@playwright/test';

test('production TLS proxy supports registration, login, research, refresh and logout', async ({ page }) => {
  const email = `browser-${Date.now()}@example.com`;
  const password = 'browser-test-password-123';
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/register');
  await page.getByLabel('Name', { exact: true }).fill('Browser Researcher');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Register', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Analyze session' })).toBeEnabled();
  const cookies = await page.context().cookies();
  const refresh = cookies.find(cookie => cookie.name === 'refresh_token');
  expect(refresh?.secure).toBe(true);
  expect(refresh?.httpOnly).toBe(true);
  await page.getByRole('button', { name: 'Analyze session' }).click();
  await page.getByRole('button', { name: 'Reveal actual next session' }).click();
  await expect(page.getByText(/What actually happened/)).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Analyze session' })).toBeEnabled();
  const rotated = (await page.context().cookies()).find(cookie => cookie.name === 'refresh_token');
  expect(rotated?.value).not.toEqual(refresh?.value);
  await page.getByRole('link', { name: 'History', exact: true }).click();
  await expect(page.getByRole('cell', { name: /RELIANCE/ }).first()).toBeVisible();
  await page.getByRole('link', { name: 'Profile', exact: true }).click();
  await expect(page.getByText('Browser Researcher', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Logout', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect((await page.context().cookies()).find(cookie => cookie.name === 'refresh_token')).toBeUndefined();
  await page.goto('/history');
  await expect(page).toHaveURL(/\/login$/);
  expect(errors).toEqual([]);
});
